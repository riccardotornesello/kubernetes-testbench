import ipaddress
from abc import ABC, abstractmethod
from typing import Any, Callable, Generic, TypeVar

from pydantic import BaseModel, ConfigDict, Field

from core.types import Settings
from utils.kubeconfig import get_kubeconfig_location
from utils.kubernetes_utils import wait_for_nodes_ready, wait_for_workloads_ready


class BaseCNISpec(BaseModel):
    """
    Parameters shared by every CNI. Each CNI subclasses this model, adding its
    own parameters and overriding the default `version`.
    """

    model_config = ConfigDict(extra="forbid")

    # CNI version to install (without the leading "v")
    version: str
    # Wait for the CNI (and the nodes) to be ready before going on
    wait: bool = True
    # Seconds to wait for the CNI to become ready
    timeout: int = Field(default=600, gt=0)

    def validate_cluster(
        self,
        cluster_cidr: ipaddress.IPv4Network,
        service_cidr: ipaddress.IPv4Network,
        nodes: int,
    ) -> None:
        """
        Validates the spec against the cluster settings. Raise ValueError on
        error. Called during the configuration validation.
        """
        return


SpecT = TypeVar("SpecT", bound=BaseCNISpec)

# A patch receives the configuration generated by the CNI (its format depends
# on the CNI, see the `install_cni` docstring of each CNI) and either modifies
# it in place and returns None, or returns the new configuration.
CNIPatch = Callable[[Any], Any]


class BaseCNI(ABC, Generic[SpecT]):
    # Reference CNI plugins (containernetworking/plugins) the CNI expects to
    # find in /opt/cni/bin on the nodes, without installing them itself.
    REQUIRED_CNI_PLUGINS: list[str] = []

    # Kernel modules the CNI needs, without loading them itself
    REQUIRED_KERNEL_MODULES: list[str] = []

    # DaemonSets/Deployments that must be ready for the CNI to be considered
    # ready, as {namespace: [names]}. None means every workload of the
    # namespace.
    WORKLOADS: dict[str, list[str] | None] = {}

    def __init__(self, cluster_name: str, settings: Settings, spec: SpecT) -> None:
        self.cluster_name = cluster_name
        self.settings = settings
        self.spec = spec
        # Customizations requested by the tools (see add_node_selector_requirement
        # and add_patch), applied by install_cni
        self.node_selector_requirements: list[dict] = []
        self._patches: list[CNIPatch] = []

    @property
    def kubeconfig(self) -> str:
        return get_kubeconfig_location(self.cluster_name)

    @property
    def replaces_kube_proxy(self) -> bool:
        """
        Whether the CNI replaces kube-proxy. If so, the runtime creates the
        cluster without kube-proxy.
        """
        return False

    def check_dependencies(self) -> None:
        return

    def add_node_selector_requirement(self, requirement: dict) -> None:
        """
        Restricts the CNI node agents to the nodes matching `requirement`, a
        Kubernetes NodeSelectorRequirement (e.g. `{"key": "foo",
        "operator": "DoesNotExist"}`). Every CNI supports it. Must be called
        before install_cni (e.g. from the tool `pre_cni_install` hook).
        """
        self.node_selector_requirements.append(requirement)

    def add_patch(self, patch: CNIPatch) -> None:
        """
        Registers a patch applied to the configuration generated by the CNI,
        right before it is installed. Patches run in registration order. The
        configuration format is CNI-specific: see the `install_cni` docstring
        of each CNI. Must be called before install_cni (e.g. from the tool
        `pre_cni_install` hook).
        """
        self._patches.append(patch)

    def apply_patches(self, config: Any) -> Any:
        for patch in self._patches:
            result = patch(config)
            if result is not None:
                config = result
        return config

    def node_affinity(self) -> dict | None:
        """
        Node affinity enforcing the node selector requirements, or None if
        there are none.
        """
        if not self.node_selector_requirements:
            return None
        return {
            "nodeAffinity": {
                "requiredDuringSchedulingIgnoredDuringExecution": {
                    "nodeSelectorTerms": [
                        {"matchExpressions": list(self.node_selector_requirements)}
                    ]
                }
            }
        }

    @abstractmethod
    def install_cni(self) -> None:
        raise NotImplementedError("Subclasses must implement this method.")

    def wait_ready(self) -> None:
        print(f"Waiting for CNI '{self.settings.cni}' to be ready")
        for namespace, names in self.WORKLOADS.items():
            wait_for_workloads_ready(
                self.kubeconfig, namespace, self.spec.timeout, names=names
            )
        wait_for_nodes_ready(self.kubeconfig, self.spec.timeout)
        # CoreDNS running means that pod networking works
        wait_for_workloads_ready(
            self.kubeconfig, "kube-system", self.spec.timeout, names=["coredns"]
        )



def find_object(objects: list[dict], kind: str, name: str) -> dict | None:
    """Returns the Kubernetes object with the given kind and name, if any."""
    return next(
        (
            obj
            for obj in objects
            if obj.get("kind") == kind and obj.get("metadata", {}).get("name") == name
        ),
        None,
    )
